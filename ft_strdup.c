#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*new;
	size_t	len;
	int		i;

	len = ft_strlen(s);
	new = malloc(len + 1);
	if (!new)
		return (NULL);
	i = 0;
	while (s[i])
	{
		new[i] = s[i];
		i++;
	}
	new[i] = 0;
	return (new);
}
